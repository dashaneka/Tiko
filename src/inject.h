/*
 * Lightweight JS bridge injected into TikTok pages.
 * - Classifies SPA routes and toggles <html> classes for CSS clean mode.
 * - Tracks the active visible <video> and active @creator handle.
 * - Reports video playback state to native GTK controls via webkit.messageHandlers.tiko.
 * - Exposes window.__tiko controls for Monet floating bar & keyboard shortcuts.
 */
static const char TIKO_BRIDGE_JS[] =
    "(function(){"
    "if(window.__tikoInstalled)return;"
    "window.__tikoInstalled=true;"
    "var focusOn=true;"
    "var lastMsg='';"
    "var root=document.documentElement;"

    "function classifyRoute(){"
    "  var host=(location.hostname||'').toLowerCase();"
    "  var p=(location.pathname||'/').toLowerCase();"
    "  if(host.indexOf('accounts.google.')>=0||host.indexOf('appleid.')>=0||host.indexOf('facebook.com')>=0)return 'login';"
    "  if(host.indexOf('tiktok.com')<0)return 'other';"
    "  root.classList.add('tiko-tiktok');"
    "  if(p.indexOf('/login')===0||p.indexOf('/signup')===0||p.indexOf('/passport')===0||p.indexOf('/auth')===0)return 'login';"
    "  if(p.indexOf('/search')===0)return 'search';"
    "  if(p==='/'||p.indexOf('/foryou')===0||p.indexOf('/following')===0||p.indexOf('/friends')===0||p.indexOf('/explore')===0)return 'feed';"
    "  if(p.indexOf('/@')===0){"
    "    if(p.indexOf('/video/')>=0||p.indexOf('/photo/')>=0)return 'video';"
    "    return 'profile';"
    "  }"
    "  if(p.indexOf('/t/')===0||p.indexOf('/video/')===0)return 'video';"
    "  return 'other';"
    "}"

    "function applyClasses(){"
    "  var r=classifyRoute();"
    "  var routes=['feed','video','profile','search','login','other'];"
    "  for(var i=0;i<routes.length;i++)root.classList.remove('tiko-route-'+routes[i]);"
    "  root.classList.add('tiko-route-'+r);"
    "  if(focusOn)root.classList.add('tiko-focus');"
    "  else root.classList.remove('tiko-focus');"
    "  return r;"
    "}"

    "function activeVideo(){"
    "  var vids=document.querySelectorAll('video');"
    "  var best=null,bestScore=-1;"
    "  var vh=window.innerHeight||800,vw=window.innerWidth||440;"
    "  for(var i=0;i<vids.length;i++){"
    "    var v=vids[i];"
    "    var rc=v.getBoundingClientRect();"
    "    if(rc.width<40||rc.height<40)continue;"
    "    var oy=Math.max(0,Math.min(rc.bottom,vh)-Math.max(rc.top,0));"
    "    var ox=Math.max(0,Math.min(rc.right,vw)-Math.max(rc.left,0));"
    "    var area=ox*oy;"
    "    if(area<=0)continue;"
    "    var score=area+(v.paused?0:vh*vw);"
    "    if(score>bestScore){bestScore=score;best=v;}"
    "  }"
    "  return best;"
    "}"

    "function extractCreator(v){"
    "  var m=(location.pathname||'').match(/^\\/@([A-Za-z0-9_.]+)/);"
    "  if(m)return '@'+m[1];"
    "  if(v){"
    "    var card=v.closest('article,[data-e2e=\"recommend-list-item-container\"],[class*=\"DivItemContainer\"],[class*=\"DivBrowserModeContainer\"]');"
    "    if(card){"
    "      var a=card.querySelector('a[href*=\"/@\"]');"
    "      if(a){"
    "        var hm=(a.getAttribute('href')||'').match(/\\/@([A-Za-z0-9_.]+)/);"
    "        if(hm)return '@'+hm[1];"
    "      }"
    "    }"
    "  }"
    "  return '';"
    "}"

    "function isTyping(){"
    "  var el=document.activeElement;"
    "  if(!el)return false;"
    "  var tag=(el.tagName||'').toUpperCase();"
    "  return tag==='INPUT'||tag==='TEXTAREA'||!!el.isContentEditable;"
    "}"

    "function sendState(force){"
    "  var route=applyClasses();"
    "  var v=activeVideo();"
    "  var creator=extractCreator(v);"
    "  var typing=isTyping()?'1':'0';"
    "  var msg=[creator,route,typing].join('\\t');"
    "  if(force||msg!==lastMsg){"
    "    lastMsg=msg;"
    "    try{window.webkit.messageHandlers.tiko.postMessage(msg);}catch(e){}"
    "  }"
    "}"

    "function stepFeed(dir){"
    "  var sel=dir>0?"
    "    ['button[data-e2e=\"arrow-right\"]','button[aria-label*=\"next\" i]','button[aria-label*=\"down\" i]']:"
    "    ['button[data-e2e=\"arrow-left\"]','button[aria-label*=\"previous\" i]','button[aria-label*=\"up\" i]'];"
    "  for(var i=0;i<sel.length;i++){"
    "    var btn=document.querySelector(sel[i]);"
    "    if(btn&&!btn.disabled){btn.click();setTimeout(function(){sendState(true);},180);return;}"
    "  }"
    "  var key=dir>0?'ArrowDown':'ArrowUp';"
    "  document.dispatchEvent(new KeyboardEvent('keydown',{key:key,code:key,bubbles:true}));"
    "  var sc=document.querySelector('#main-content-homepage_hot,#main-content-homepage_follow,[class*=\"DivColumnListContainer\"]')||document.scrollingElement;"
    "  if(sc&&sc.scrollBy)sc.scrollBy({top:dir*window.innerHeight,behavior:'smooth'});"
    "  else window.scrollBy({top:dir*window.innerHeight,behavior:'smooth'});"
    "  setTimeout(function(){sendState(true);},220);"
    "}"

    "window.__tiko={"
    "  setFocus:function(on){focusOn=!!on;sendState(true);},"
    "  togglePlay:function(){"
    "    var v=activeVideo();"
    "    if(!v)return;"
    "    if(v.paused)v.play().catch(function(){});else v.pause();"
    "  },"
    "  toggleMute:function(){"
    "    var v=activeVideo();"
    "    if(!v)return;"
    "    v.muted=!v.muted;"
    "    if(!v.muted&&v.volume===0)v.volume=0.8;"
    "  },"
    "  seekBy:function(delta){"
    "    var v=activeVideo();"
    "    if(!v||!isFinite(v.duration)||v.duration<=0)return;"
    "    v.currentTime=Math.max(0,Math.min(v.duration,v.currentTime+delta));"
    "  },"
    "  next:function(){stepFeed(1);},"
    "  prev:function(){stepFeed(-1);}"
    "};"

    /* Hook SPA navigation & focus changes */
    "var _ps=history.pushState,_rs=history.replaceState;"
    "history.pushState=function(){var r=_ps.apply(this,arguments);setTimeout(function(){sendState(true);},60);return r;};"
    "history.replaceState=function(){var r=_rs.apply(this,arguments);setTimeout(function(){sendState(true);},60);return r;};"
    "window.addEventListener('popstate',function(){setTimeout(function(){sendState(true);},60);});"
    "document.addEventListener('focusin',function(){sendState(true);},true);"
    "document.addEventListener('focusout',function(){sendState(true);},true);"
    "applyClasses();"
    "setInterval(function(){sendState(false);},400);"
    "sendState(true);"
    "})();";

